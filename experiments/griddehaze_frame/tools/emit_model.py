"""Emit hardware constants from the audited, frozen INT16 bundle; no model change."""
import argparse
import json
from pathlib import Path
from preflight import ROOT,audit,plan,sha

OPS={'input':0,'conv':1,'deconv':2,'relu':3,'mulcoef':4,'add':5,'cat':6}

def emit(target):
    m,g,p,_=audit(ROOT/'a_candidate/package')
    memory=plan(g,p,33,47)
    indices={n['id']:i for i,n in enumerate(g['nodes'])}
    shifts=[]; rows=[]
    for n,r in zip(g['nodes'],memory['nodes']):
        args=n['inputs']; soff=len(shifts)
        shifts+=n.get('requantization_shift',[])
        rows.append([OPS[n['op']],indices[args[0]] if args else 0,indices[args[1]] if len(args)>1 else 0,
            indices[n['output_like']] if 'output_like' in n else 0,r['shape'][0],n['activation_frac'],
            n.get('kernel_size',[0])[0],n.get('stride',[1])[0],n.get('padding',[0])[0],r['last_use'],
            p[n['weight']][0]['offset']//2 if 'weight' in n else 0,
            p[n['bias']][0]['offset']//2 if 'bias' in n else 0,
            p[n['coefficient']][0]['offset']//2 if 'coefficient' in n else 0,soff])
    words=[int.from_bytes(bytes.fromhex(m['identity']['bundle_id'])[i:i+4],'little') for i in range(0,32,4)]
    lines=['#pragma once','#include <cstdint>',
        '// Generated by tools/emit_model.py from graph SHA256 '+m['graph_sha256'],
        'namespace gdn_model {',
        'constexpr std::uint32_t MODEL_ID=0x47444E31u, ABI=0x00010000u;',
        'constexpr int NODES=320;',f'constexpr std::uint32_t PARAMETER_BYTES={m["blob_nbytes"]}u;',
        'struct Node { std::uint16_t op,a,b,like,channels,frac,kernel,stride,padding,last_use; std::uint32_t weight,bias,coefficient,shift; };',
        'static const Node graph[NODES]={',*['    {'+','.join(map(str,r))+'},' for r in rows],'};',
        'static const std::int8_t shifts[]={'+','.join(map(str,shifts))+'};',
        'static const std::uint32_t bundle[8]={'+','.join(hex(w)+'u' for w in words)+'};','} // namespace gdn_model','']
    target=Path(target)
    if target.exists(): raise FileExistsError(target)
    target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text('\n'.join(lines),encoding='ascii')
    print(json.dumps(dict(path=str(target),sha256=sha(target),bundle_id=m['identity']['bundle_id'],nodes=len(rows),shifts=len(shifts))))

def layout(path,h,w):
    import struct
    m,g,p,_=audit(ROOT/'a_candidate/package')
    memory=plan(g,p,h,w)
    words=[0x314c4447,1,h,w,320,0,memory['scratch_bytes'],0]
    words += [int.from_bytes(bytes.fromhex(m['identity']['bundle_id'])[i:i+4],'little') for i in range(0,32,4)]
    words += [n['offset'] if n['region']=='scratch' else 0 for n in memory['nodes']]
    Path(path).write_bytes(struct.pack('<'+'I'*len(words),*words))
    return memory

if __name__=='__main__':
    p=argparse.ArgumentParser(__doc__);p.add_argument('--out',type=Path,required=True)
    a=p.parse_args();emit(a.out)
