"""Extract only manifest-verified 8x8 smoke fixtures into a C header."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--delivery', type=Path, required=True)
p.add_argument('--output', type=Path, required=True)
a = p.parse_args()
delivery = a.delivery.resolve()
manifest_path = delivery.parents[1] / 'DELIVERY_MANIFEST.json'
entries = {e['path']: e for e in json.loads(manifest_path.read_text(encoding='utf-8'))['files']}
lines = ['/* Manifest-verified A-group 8x8 Q14 fixtures; generated by prepare_smoke_vectors.py. */',
         '#ifndef WEATHER_SMOKE_VECTORS_H', '#define WEATHER_SMOKE_VECTORS_H', '#include <stdint.h>']
for task in ('derain', 'dehaze'):
    for endpoint in ('input', 'output'):
        path = delivery / 'evidence/hls/rtl_depth_fix_20261020' / task / 'fixtures' / ('cosim_' + endpoint + '.bin')
        raw = path.read_bytes()
        entry = entries[path.relative_to(manifest_path.parent).as_posix()]
        digest = hashlib.sha256(raw).hexdigest()
        if len(raw) != 384 or entry['bytes'] != len(raw) or entry['sha256'] != digest:
            raise RuntimeError('fixture mismatch: ' + str(path))
        lines += ['/* SHA256 ' + digest + ' */', 'static const int16_t ' + task + '_' + endpoint + '[192] = {']
        values = struct.unpack('<192h', raw)
        for i in range(0, 192, 12):
            lines.append('    ' + ', '.join(map(str, values[i:i+12])) + ',')
        lines.append('};')
lines += ['#endif', '']
with a.output.open('x', encoding='utf-8') as f:
    f.write('\n'.join(lines))
print('SMOKE_VECTORS_PASS', a.output)
